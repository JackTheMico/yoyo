#!/usr/bin/env python3
"""#51 生成码元→键位映射数据。

产物：
  rime/lua/yoyo/data/cj_keymap.lua      —— 引擎/键盘层共同消费的映射数据
  docs/design/cj-keymap-table.md        —— 人读映射表

频次口径
--------
码元频次 = 该码元在 yoyo-pure.dict.yaml 全部条目（单字 + 词）的编码串里
出现的次数之和。不含 `_` / `+` 两个前缀，因为它们不是可敲的码元。

为什么按「出现次数」而不是「按词频加权」
----------------------------------------
出现次数衡量的是「敲字时手指要落多少次」，这正是键位分配要优化的量。
按词频加权会把少数超高频字的码元权重放大到失真（例如 `的` 单个字就能
压过几百个词），反而偏离「减少总击键距离」的目标。两者都算，差异记在
docs/design/cj-keymap-table.md 末尾供对照。

三档落位规则
------------
1. 26 个小写码元 → 26 个字母键，点击层，同名直映射。
2. 8 个符号码元 → 8 个符号键，点击层。符号只有 8 个、符号键也正好 8 个，
   所以按同名直映射（零学习成本），不参与频次竞争。若改按频次分配，
   `;` 这类高频符号会被挤到数字行，而它本来的键位反而闲置——纯亏。
3. 26 个大写码元：
   a. 频次最高的 10 个 → 数字行 10 键，点击层（按拇指易达性排序落位）。
   b. 其余 16 个 → 同名小写字母键的上滑层。

拇指易达性
----------
竖屏双手持握，两拇指的舒适区都在屏幕中下部靠中线的位置，越靠外缘越难够。
数字键的易达评分（高→低）：5, 6, 4, 7, 3, 8, 2, 9, 1, 0。
注：这是模型参数，不是实测值，真机手感需另行验证（见 #57）。

运行：/usr/bin/python3 rime/scripts/gen_cj_keymap.py
"""

import collections
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
DICT = ROOT / "rime/yoyo-pure.dict.yaml"
OUT_LUA = ROOT / "rime/lua/yoyo/data/cj_keymap.lua"
OUT_MD = ROOT / "docs/design/cj-keymap-table.md"

PREFIXES = {"_", "+"}
SYMBOLS = ";:,./<>?"
DIGIT_REACH_ORDER = ["5", "6", "4", "7", "3", "8", "2", "9", "1", "0"]

LAYER_LABEL = {
    "letter": "字母键",
    "digit": "数字键",
    "symbol": "符号键",
    "swipe_up": "上滑层",
}


def read_entries():
    """读出 (文本, 编码) 条目。"""
    out = []
    body = False
    for line in DICT.read_text(encoding="utf-8").splitlines():
        if line.startswith("..."):
            body = True
            continue
        if not body:
            continue
        parts = line.split("\t")
        if len(parts) < 2:
            continue
        out.append((parts[0], parts[1].strip()))
    return out


def code_units(entries):
    units = set()
    for _, code in entries:
        units.update(code)
    return units - PREFIXES


def unit_frequencies(entries):
    """码元出现次数（全表，含单字与词）。"""
    cnt = collections.Counter()
    for _, code in entries:
        for ch in code:
            if ch not in PREFIXES:
                cnt[ch] += 1
    return cnt


def build_keymap(units, freq):
    upper = sorted([u for u in units if u.isupper()], key=lambda u: (-freq[u], u))
    lower = sorted([u for u in units if u.islower()])
    symbols = sorted([u for u in units if u in SYMBOLS])

    if len(lower) != 26 or len(upper) != 26 or len(symbols) != 8:
        raise SystemExit(
            f"码元构成异常：小写 {len(lower)} / 大写 {len(upper)} / 符号 {len(symbols)}，"
            "预期 26/26/8。码表结构变了，本脚本的落位规则需重新设计。"
        )

    entries = []
    for u in lower:
        entries.append({"code": u, "key": u, "layer": "letter", "via": "text",
                        "freq": freq[u]})
    for u in symbols:
        entries.append({"code": u, "key": u, "layer": "symbol", "via": "text",
                        "freq": freq[u]})

    digit_bound = upper[:10]
    swipe_bound = upper[10:]
    for u, digit in zip(digit_bound, DIGIT_REACH_ORDER):
        entries.append({"code": u, "key": digit, "layer": "digit", "via": "text",
                        "freq": freq[u]})
    for u in swipe_bound:
        entries.append({"code": u, "key": u.lower(), "layer": "swipe_up",
                        "via": "text", "freq": freq[u]})

    # 上滑层按字母序输出，便于人工核对
    entries.sort(key=lambda e: (
        ["letter", "digit", "symbol", "swipe_up"].index(e["layer"]),
        e["key"] if e["layer"] != "digit" else DIGIT_REACH_ORDER.index(e["key"]),
    ))
    return entries, digit_bound, swipe_bound


def emit_lua(entries, total_units_seen):
    lines = [
        "-- Auto-generated by rime/scripts/gen_cj_keymap.py —— 请勿手改",
        "-- 码元 → 触摸键位映射（yoyo-pure-cj 串击版）",
        "--",
        "-- layer: letter（字母键点击）/ digit（数字行点击）/ symbol（符号键点击）",
        "--        / swipe_up（字母键上滑）",
        "-- via:   键盘层应使用的键动作类型。必须是 `text`（字面量字符），",
        "--        不能用 Shift 修饰——librime 的 KeyEvent 只看 keycode，",
        "--        Shift+k 送进去仍是小写 k（见 docs/design/2026-10-26-cj-keyboard-delivery.md）。",
        "",
        "local M = {",
        f"  code_unit_count = {total_units_seen},",
        "  entries = {",
    ]
    for e in entries:
        lines.append(
            f'    {{ code = "{e["code"]}", key = "{e["key"]}", '
            f'layer = "{e["layer"]}", via = "{e["via"]}", freq = {e["freq"]} }},'
        )
    lines += [
        "  },",
        "}",
        "",
        "-- 按码元索引，状态机查询用",
        "M.by_code = {}",
        'for _, e in ipairs(M.entries) do M.by_code[e.code] = e end',
        "",
        "-- 按物理键索引，键盘层生成用；一个键可能同时有点击层与上滑层",
        "M.by_key = {}",
        "for _, e in ipairs(M.entries) do",
        "  M.by_key[e.key] = M.by_key[e.key] or {}",
        "  M.by_key[e.key][e.layer] = e.code",
        "end",
        "",
        "return M",
        "",
    ]
    OUT_LUA.parent.mkdir(parents=True, exist_ok=True)
    OUT_LUA.write_text("\n".join(lines), encoding="utf-8")


def emit_md(entries, freq, digit_bound, swipe_bound, entries_raw):
    by_layer = collections.defaultdict(list)
    for e in entries:
        by_layer[e["layer"]].append(e)

    out = [
        "# yoyo-pure-cj 码元→键位映射表",
        "",
        "> 由 `rime/scripts/gen_cj_keymap.py` 生成，请勿手改。数据源 `rime/yoyo-pure.dict.yaml`。",
        "",
        "## 总览",
        "",
        "| 层 | 键位数 | 承载码元 | 按键动作 |",
        "|---|---|---|---|",
        f"| 字母键（点击） | 26 | 小写码元 | `text` |",
        f"| 数字键（点击） | 10 | 高频大写码元 | `text` |",
        f"| 符号键（点击） | 8 | 符号码元 | `text` |",
        f"| 字母键（上滑） | 16 | 其余大写码元 | `text` |",
        "",
        "共 60 码元，落 44 个物理键。",
        "",
        "## 字母键点击层",
        "",
        "| 码元 | 键位 | 频次 |",
        "|---|---|---|",
    ]
    for e in sorted(by_layer["letter"], key=lambda x: x["key"]):
        out.append(f"| `{e['code']}` | `{e['key']}` | {e['freq']} |")

    out += ["", "## 数字键点击层（按拇指易达性落位）", "",
            "| 码元 | 键位 | 易达序 | 频次 |", "|---|---|---|---|"]
    digit_order = {e["key"]: i + 1 for i, e in enumerate(
        sorted(by_layer["digit"], key=lambda x: DIGIT_REACH_ORDER.index(x["key"])))}
    for e in sorted(by_layer["digit"], key=lambda x: DIGIT_REACH_ORDER.index(x["key"])):
        out.append(f"| `{e['code']}` | `{e['key']}` | {digit_order[e['key']]} | {e['freq']} |")

    out += ["", "## 符号键点击层（同名直映射）", "", "| 码元 | 键位 | 频次 |", "|---|---|---|"]
    for e in sorted(by_layer["symbol"], key=lambda x: SYMBOLS.index(x["code"]) if x["code"] in SYMBOLS else 99):
        out.append(f"| `{e['code']}` | `{e['key']}` | {e['freq']} |")

    out += ["", "## 字母键上滑层", "",
            "上滑键位与码元的小写字母同名：按住 `q` 键上滑出码元 `Q`。", "",
            "| 码元 | 键位 | 频次 |", "|---|---|---|"]
    for e in sorted(by_layer["swipe_up"], key=lambda x: x["key"]):
        out.append(f"| `{e['code']}` | `{e['key']}` ↑ | {e['freq']} |")

    total_occ = sum(freq.values())
    upper_freq = sum(freq[u] for u in digit_bound) + sum(freq[u] for u in swipe_bound)
    nonlower_occ = sum(v for k, v in freq.items() if not k.islower())

    out += [
        "",
        "## 频次口径与依据",
        "",
        f"- 码元出现总次数 **{total_occ}**（全部 {len(entries_raw)} 条条目、单字与词合计）。",
        "- 频次 = 该码元在所有编码串里出现的次数，不是包含它的条目数。",
        "- 不计 `_`（左手前缀）与 `+`（右手前缀）：它们是并击版的定界符，串击版不使用。",
        "",
        "### 为何按出现次数而非词频加权",
        "",
        "出现次数直接对应「手指要落多少次」，是键位分配要优化的量。按词频加权会让",
        "少数超高频字（如「的」）的码元权重失真放大，压过几百个词，反而偏离目标。",
        "",
        "### 独立键位覆盖率",
        "",
        f"- 非小写码元总频次 **{nonlower_occ}**，占全部码元 **{nonlower_occ / total_occ * 100:.1f}%**。",
        f"- 18 个独立键位（数字 10 + 符号 8）承载其中 {sum(freq[u] for u in digit_bound) + sum(freq[k] for k in SYMBOLS if k in freq)} 次，"
        f"占非小写码元 **{(sum(freq[u] for u in digit_bound) + sum(freq[k] for k in SYMBOLS if k in freq)) / nonlower_occ * 100:.1f}%**。",
        f"- 上滑层 16 个码元合计 {sum(freq[u] for u in swipe_bound)} 次，占全部码元 **{sum(freq[u] for u in swipe_bound) / total_occ * 100:.1f}%**。",
        "",
        "### 大写码元的分配依据",
        "",
        "大写码元按频次降序，前 10 个进数字行，其余 16 个进上滑层：",
        "",
        "| 序 | 码元 | 频次 | 去向 |",
        "|---|---|---|---|",
    ]
    uppers = sorted(digit_bound + swipe_bound, key=lambda u: -freq[u])
    digit_set = set(digit_bound)
    for i, u in enumerate(uppers, 1):
        out.append(f"| {i} | `{u}` | {freq[u]} | {'数字键' if u in digit_set else '上滑'} |")

    out += [
        "",
        "## 必须遵守的约束",
        "",
        "1. **键盘层必须用 `text` 动作送字面量字符**，不能用 Shift 修饰键。实测：",
        "   `process_key('k', kShiftMask)` 送进 librime 后仍是小写 `k`，会静默落到另一个",
        "   合法码位、打出另一个字（`.k` → 「瑜伽」而非 `.K` → 「猷」）。",
        "2. **数字键被征用后不能再用数字选候选**。候选选择走点按候选栏；这是触摸键盘的",
        "   天然交互，不构成功能损失。",
        "3. **本映射与 `speller.alphabet` 必须一致**，由 `test_cj_keymap.py` 自动校验。",
        "   错一位就是静默打错字，改动映射后必须重跑校验。",
        "",
    ]
    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text("\n".join(out), encoding="utf-8")


def main():
    entries_raw = read_entries()
    units = code_units(entries_raw)
    freq = unit_frequencies(entries_raw)
    entries, digit_bound, swipe_bound = build_keymap(units, freq)
    emit_lua(entries, len(units))
    emit_md(entries, freq, digit_bound, swipe_bound, entries_raw)
    print(f"码元 {len(units)} 个 → 落键 {len(entries)} 条")
    print(f"字典条目 {len(entries_raw)}，码元出现总次数 {sum(freq.values())}")
    print(f"输出 {OUT_LUA.relative_to(ROOT)} 与 {OUT_MD.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
