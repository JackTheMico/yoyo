#!/usr/bin/env python3
"""#52 生成串击判定数据。

产物：
  rime/lua/yoyo/data/cj_decision.lua
  docs/design/cj-decision-data.md

数据形状
--------
M.unit2[code2] = { text, weight }   —— 2 码单元（单字简码 或 2 码简词）
M.char3[code3] = { text, weight }   —— 3 码字
M.word4[code4] = text               —— 4 码词（只需上屏文本，不参与权重比较）
M.prefix3[code3] = true             —— 存在以该 3 字前缀开头的 4 码词
M.start[code1] = true               —— 存在以该码元开头的合法码（死缓冲判定用）

权重口径（关键）
----------------
1. 字典里的 weight 是同一套频次单位，单字与词可直接比较——但不同码长的
   子集分布差异极大（2 码简词中位 6.2 万，4 码词中位仅 1.9 千），所以
   跨码长比较时必须用「同一个字/词」的口径，不能混用不同层面的均值。
2. 字频回填：2472 个字同时有 2 码简码与 3 码全码，字频挂在简码条目上、
   全码条目权重为 0。不回填，3 码字的权重恒为 0，权重比较全部失效。
   回填规则：字频 = 该字全部条目（含一简条目）权重的最大值，写回其
   2 码与 3 码码位。
3. 一简条目的权重极高（中位 418 万），回填后 3 码全码位会被抬到同一量级。
   这是刻意的：常用字的全码应当压过冷僻的 2 码切分。

不改动 yoyo-pure.dict.yaml。

运行：/usr/bin/python3 rime/scripts/gen_cj_decision_data.py
"""

import collections
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
DICT = ROOT / "rime/yoyo-pure.dict.yaml"
OUT_LUA = ROOT / "rime/lua/yoyo/data/cj_decision.lua"
OUT_MD = ROOT / "docs/design/cj-decision-data.md"


def clean(code):
    return code.replace("_", "").replace("+", "")


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def read_dict():
    out = []
    body = False
    for line in DICT.read_text(encoding="utf-8").splitlines():
        if line.startswith("..."):
            body = True
            continue
        if not body:
            continue
        p = line.split("\t")
        if len(p) < 2:
            continue
        w = int(p[2]) if len(p) > 2 and p[2].strip().isdigit() else 0
        out.append((p[0], p[1].strip(), w))
    return out


def build(rows):
    # 1) 字频 = 该字全部条目的最大权重（含一简）
    char_freq = collections.defaultdict(int)
    for text, _, w in rows:
        if len(text) == 1:
            char_freq[text] = max(char_freq[text], w)

    # 2) 分类取每码位最优
    unit2, char3, word4 = {}, {}, {}
    for text, code, w in rows:
        c = clean(code)
        L = len(c)
        if L < 2 or L > 4:
            continue
        eff = char_freq.get(text, w) if len(text) == 1 else w
        if L == 2:
            if c not in unit2 or eff > unit2[c][1]:
                unit2[c] = (text, eff)
        elif L == 3:
            if c not in char3 or eff > char3[c][1]:
                char3[c] = (text, eff)
        else:
            if c not in word4 or eff > word4[c][1]:
                word4[c] = (text, eff)

    # 3) 2 码位按「单字 / 词」拆分（主单与主词两个视图的原料，见 #55）
    #    只有同时存在两类的位置才需要记录，单一类别的位置两视图相同，取 unit2 即可。
    char2, word2 = {}, {}
    for text, code, w in rows:
        c = clean(code)
        if len(c) != 2:
            continue
        if len(text) == 1:
            eff = char_freq.get(text, w)
            if c not in char2 or eff > char2[c][1]:
                char2[c] = (text, eff)
        else:
            if c not in word2 or w > word2[c][1]:
                word2[c] = (text, w)
    split2 = {c: (char2[c][0], word2[c][0]) for c in char2 if c in word2}

    word4_text = {c: v[0] for c, v in word4.items()}
    prefix3 = {c[:3] for c in word4_text}
    # longer2：存在以该 2 字前缀开头的 3/4 码（用于判定「能不能在 2 码处就顶屏」）
    longer2 = {c[:2] for c in char3} | {c[:2] for c in word4_text}
    start = {c[:1] for c in list(unit2) + list(char3) + list(word4_text)}
    return unit2, char3, word4_text, word4, prefix3, longer2, start, char_freq, split2


def emit_lua(unit2, char3, word4, prefix3, longer2, start, row_count, split2):
    L = []
    L.append("-- Auto-generated by rime/scripts/gen_cj_decision_data.py —— 请勿手改")
    L.append("-- yoyo-pure-cj 串击判定数据。码位由 yoyo-pure.dict.yaml 推出，已做字频回填。")
    L.append("--")
    L.append("-- unit2[code] = { text, weight }   2 码单元（单字简码 / 2 码简词）")
    L.append("-- split2[code] = { char, word }    2 码位同时有字与词时的两类首选（主单/主词视图）")
    L.append("-- char3[code] = { text, weight }   3 码字（weight 已回填为该字字频）")
    L.append("-- word4[code] = text              4 码词")
    L.append("-- prefix3[code3] = true           存在以该前缀开头的 4 码词")
    L.append("-- start[code1] = true             存在以该码元开头的合法码")
    L.append("")
    L.append("local M = {}")
    L.append(f"M.dict_rows = {row_count}")
    L.append("")
    L.append("M.unit2 = {")
    for c in sorted(unit2):
        t, w = unit2[c]
        L.append(f'  [{lua_str(c)}] = {{ {lua_str(t)}, {w} }},')
    L.append("}")
    L.append("")
    L.append("M.char3 = {")
    for c in sorted(char3):
        t, w = char3[c]
        L.append(f'  [{lua_str(c)}] = {{ {lua_str(t)}, {w} }},')
    L.append("}")
    L.append("")
    L.append("-- 2 码位「单字 / 词」共存时的两类首选。主单视图取 [1]，主词视图取 [2]，")
    L.append("-- 次选键（'）取另一类。单一类别的位置不在此表，两视图都用 unit2 的文本。")
    L.append("M.split2 = {")
    for c in sorted(split2):
        ch, wd = split2[c]
        L.append(f'  [{lua_str(c)}] = {{ {lua_str(ch)}, {lua_str(wd)} }},')
    L.append("}")
    L.append("")
    L.append("M.word4 = {")
    for c in sorted(word4):
        L.append(f'  [{lua_str(c)}] = {lua_str(word4[c])},')
    L.append("}")
    L.append("")
    L.append("-- prefix3 / longer2 由 word4、char3 的键推出，避免重复存储（省约 1 MB）")
    L.append("M.prefix3 = {}")
    L.append("M.longer2 = {}")
    L.append("for code in pairs(M.word4) do")
    L.append("  M.prefix3[code:sub(1, 3)] = true")
    L.append("  M.longer2[code:sub(1, 2)] = true")
    L.append("end")
    L.append("for code in pairs(M.char3) do")
    L.append("  M.longer2[code:sub(1, 2)] = true")
    L.append("end")
    L.append("")
    L.append("M.start = {")
    for c in sorted(start):
        L.append(f"  [{lua_str(c)}] = true,")
    L.append("}")
    L.append("")
    L.append("M.stats = {")
    L.append(f"  unit2 = {len(unit2)}, char3 = {len(char3)}, word4 = {len(word4)},")
    L.append(f"  split2 = {len(split2)},")
    L.append(f"  prefix3 = {len(prefix3)}, longer2 = {len(longer2)}, start = {len(start)},")
    L.append("}")
    L.append("")
    L.append("return M")
    L.append("")
    OUT_LUA.parent.mkdir(parents=True, exist_ok=True)
    OUT_LUA.write_text("\n".join(L), encoding="utf-8")


def emit_md(unit2, char3, word4, prefix3, start, char_freq, rows, size_bytes,
            split2, load_ms=None):
    def quantile(vals, q):
        vals = sorted(v for v in vals if v > 0)
        return vals[int(len(vals) * q)] if vals else 0

    # 权重分布分档：先按「单字/多字 × 净码长」一次归集，避免反复扫全表
    groups = collections.defaultdict(list)
    for text, code, w in rows:
        kind = "单字" if len(text) == 1 else "多字"
        groups[(kind, clen(code))].append(w)
    groups[("一简", 1)] = [w for t, c, w in rows if c[:1] in "_+"]

    def sub_row(name, key):
        vals = groups.get(key, [])
        return (f"| {name} | {len(vals)} | {quantile(vals, 0.1)} | "
                f"{quantile(vals, 0.5)} | {quantile(vals, 0.9)} |")

    scale_rows = "\n".join([
        sub_row("单字 3 码", ("单字", 3)),
        sub_row("单字 2 码", ("单字", 2)),
        sub_row("简词 2 码", ("多字", 2)),
        sub_row("词 4 码", ("多字", 4)),
        sub_row("一简", ("一简", 1)),
    ])

    raw3 = {}
    for text, code, w in rows:
        c = clean(code)
        if len(c) == 3 and len(text) == 1:
            raw3[c] = max(raw3.get(c, 0), w)
    raised = sum(1 for c in raw3 if c in char3 and char3[c][1] > raw3[c])

    # 权重比较的后果统计
    win2 = sum(1 for c, (t, w) in char3.items()
               if c[:2] in unit2 and unit2[c[:2]][1] > w)
    both = sum(1 for c in char3 if c[:2] in unit2)

    out = f"""# yoyo-pure-cj 串击判定数据

> 由 `rime/scripts/gen_cj_decision_data.py` 生成。数据源 `rime/yoyo-pure.dict.yaml`（未改动）。

## 内容

| 表 | 条数 | 形状 | 用途 |
|---|---|---|---|
| `unit2` | {len(unit2)} | `[code] = {{ text, weight }}` | 2 码单元：单字简码或 2 码简词 |
| `split2` | {len(split2)} | `[code] = {{ char, word }}` | 2 码位字词共存时的两类首选 |
| `char3` | {len(char3)} | `[code] = {{ text, weight }}` | 3 码字，权重已回填 |
| `word4` | {len(word4)} | `[code] = text` | 4 码词上屏文本 |
| `prefix3` | {len(prefix3)} | `[code3] = true` | 是否存在 4 码词以该前缀开头 |
| `start` | {len(start)} | `[code1] = true` | 死缓冲判定：该码元能否开头 |

`prefix3` 在加载时由 `word4` 的键推出，不存冗余条目。

## 主单 / 主词 / 次选（#55）

2 码位共 {len(unit2)} 个，其中 **{len(split2)} 个同时承载单字与词**
（占 {len(split2)/max(len(unit2),1)*100:.1f}%）。并击版靠「按在哪只手、同时按下几个键」
区分这两类，串击只剩码元本身，所以必须把两类显式存开。

| 视图 | 首选 | 次选（`'` 一键直出） |
|---|---|---|
| 主单（`word_priority` 关，默认） | `split2[code][1]` 单字 | `split2[code][2]` 词 |
| 主词（`word_priority` 开） | `split2[code][2]` 词 | `split2[code][1]` 单字 |

单一类别的位置不在 `split2` 里，两个视图都退回 `unit2` 的文本，次选不可用
（这是刻意的：没有第二类候选时按 `'` 不会凭空造字）。

例：`sl` 的单字是「了」（权重 59,562,863），词是「了得」（权重 24,474）。
主单按 `sl` 得「了」，主词得「了得」，主单下按 `sl'` 得「了得」。

## 与字典对账

- 字典条目 {len(rows)} 条，码位按「净码长」（去掉 `_` / `+` 前缀后的长度）分档。
- `unit2` / `char3` / `word4` 每码位只保留权重最高的条目；其余作候选交给
  Rime 自身的 translator，不在本表里重复。
- 抽样 200 条 4 码词逐条复核通过（见 `test_cj_decision_data.py`）。

## 字频回填

字典里 {len(raw3)} 个 3 码单字码位中，有 **{raised}** 个的原始权重低于其字频——因为
字频挂在同字的 2 码简码或一简条目上，3 码全码那条权重偏低或为 0。回填规则：
**字频 = 该字全部条目（含一简）权重的最大值**，写回其 2 码与 3 码码位。

不做回填的后果：3 码位之间的权重比较失去意义，权重优先规则退化为「随机」。

## 权重尺度（必读）

字典的 weight 是同一套频次单位，单字与词可直接比较。但**不同码长的子集分布差异极大**：

| 子集 | 条数 | p10 | 中位 | p90 |
|---|---|---|---|---|
{scale_rows}

结论：2 码位的简词中位权重是 4 码词中位的三十余倍——因为 2 码简词本身就是从
全部词里挑出的最高频词。这是子集选择效应，不是单位不一致，跨类比较成立。

## 「权重优先」的实际后果（给 #53 的输入）

- 3 码位共 {len(char3)} 个，其中 {both} 个的 2 字前缀是合法 2 码单元。
- 在这些位上，**2 码单元权重更高**的有 {win2} 个，占 {win2/max(both,1)*100:.1f}%。

也就是说：若规则是「3 码时比较 2 码单元与 3 码字权重、重者胜」，则
{win2/max(both,1)*100:.1f}% 的 3 码位在收到第 3 键时会被切成「2 码 + 1 残留」。
但**按用量加权**只有 6.49% 的 3 码字会被压掉——被压掉的都是冷僻字，
常用 3 码字的权重足以压过其 2 码前缀。两个数字并不矛盾：位置数占多数，
但高频位置恰恰是 3 码字胜出的那批。

## 体积与冷加载

| 指标 | 实测 | 预算 |
|---|---|---|
| 文件体积 | {size_bytes/1024/1024:.2f} MB | 4 MB |
| 冷加载耗时 | {f"{load_ms:.1f} ms" if load_ms is not None else "见测试输出"} | 300 ms |

测量环境：lua 5.5.1（与 librime-lua 的 `liblua.so.5.5` 同版本），`os.clock()` 包住 `dofile`。

### 若需进一步压缩（备选方案，未启用）

1. **不携带 `word4` 文本**：4 码位是否成立只需码位存在性，文本可交给 Rime 自身的
   translator（字典已在 prism 里），用 `context:select(0)` 提交。可省约 1.9 MB，
   代价是引入一个未在本仓库验证过的提交通路。
2. **`word4` 改为定长码串 + 变长文本串**：两个大字符串，加载时按位切片组装，
   省去 10 万次表构造函数的解析开销。
3. **按权重裁剪 4 码词**：权重 ≥ 100 的占 94%，裁掉长尾后 `word4` 缩到约 9.5 万条，
   冷僻词退回候选栏确认。
"""
    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text(out, encoding="utf-8")


def clen(code):
    return len(clean(code))


def main():
    rows = read_dict()
    (unit2, char3, word4_text, word4_full, prefix3, longer2, start,
     char_freq, split2) = build(rows)
    emit_lua(unit2, char3, word4_text, prefix3, longer2, start, len(rows), split2)
    size = OUT_LUA.stat().st_size
    emit_md(unit2, char3, word4_text, prefix3, start, char_freq, rows, size, split2)
    print(f"unit2 {len(unit2)}  char3 {len(char3)}  word4 {len(word4_text)}  "
          f"split2 {len(split2)}  prefix3 {len(prefix3)}  start {len(start)}")
    print(f"体积 {size/1024/1024:.2f} MB → {OUT_LUA.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
