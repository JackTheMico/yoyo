#!/usr/bin/env python3
"""#56 生成快捷字条字表。

产物：
  rime/lua/yoyo/data/cj_quickbar.lua
  docs/design/cj-quickbar.md

为什么要字条
------------
串击版取消了编码层的一简（一击出高频字）。这不是取舍，是硬约束：
60 个码元已占满单键，2 码组合又被 2 码字占用 97%，编码层没有第二层可用。
补偿通道是键盘上方的可点字条——点一下直出，不占编码空间，零冲突。

口径
----
字频与判定数据同源同法：**该字全部条目（含一简）权重的最大值**。
码取该字最短的可打码（2 码优先于 3 码），且必须存在于判定数据的
unit2 / char3 中——否则字条点了也打不出来。

运行：/usr/bin/python3 rime/scripts/gen_cj_quickbar.py
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
DICT = ROOT / "rime/yoyo-pure.dict.yaml"
OUT_LUA = ROOT / "rime/lua/yoyo/data/cj_quickbar.lua"
OUT_MD = ROOT / "docs/design/cj-quickbar.md"

SLOTS = 12
# 键值只用于键盘层做「第几格」的标识，不是 Rime 按键。1-9 0 - =
KEYS = ["1", "2", "3", "4", "5", "6", "7", "8", "9", "0", "-", "="]


def clean(code):
    return code.replace("_", "").replace("+", "")


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def read_dict():
    rows, body = [], False
    for line in DICT.read_text(encoding="utf-8").splitlines():
        if line.startswith("..."):
            body = True
            continue
        if not body:
            continue
        p = line.split("\t")
        if len(p) < 2:
            continue
        w = int(p[2]) if len(p) > 2 and p[2].strip().isdigit() else 0
        rows.append((p[0], p[1].strip(), w))
    return rows


def build(rows):
    # 字频：与 gen_cj_decision_data.py 完全同一口径
    freq = {}
    for text, code, w in rows:
        if len(text) == 1:
            freq[text] = max(freq.get(text, 0), w)

    # 最短可打码
    codes = {}
    for text, code, w in rows:
        c = clean(code)
        if len(text) != 1 or len(c) not in (2, 3):
            continue
        if text not in codes or len(c) < len(codes[text]):
            codes[text] = c

    cand = [(ch, codes[ch], freq[ch]) for ch in codes if freq.get(ch, 0) > 0]
    cand.sort(key=lambda x: (-x[2], x[0]))
    return cand[:SLOTS]


def emit_lua(picked):
    L = []
    L.append("-- Auto-generated by rime/scripts/gen_cj_quickbar.py —— 请勿手改")
    L.append("-- yoyo-pure-cj 快捷字条：最高频的 %d 个字，供键盘层点击直出。" % SLOTS)
    L.append("--")
    L.append("-- 存在理由：串击版取消了编码层一简（60 码元占满单键、2 码组合被 2 码字占 97%），")
    L.append("-- 最高频字改由键盘上方的可点字条补偿，不占编码空间。")
    L.append("--")
    L.append("-- slots[i].key  键盘层格位标识（1-9 0 - =），不是 Rime 按键")
    L.append("-- slots[i].char 点击后上屏的文本")
    L.append("-- slots[i].code 该字在本方案里的最短码（仅作提示，点击不经过状态机）")
    L.append("-- slots[i].freq 字频（= 该字全部条目权重的最大值，与判定数据同口径）")
    L.append("")
    L.append("local M = {}")
    L.append("")
    L.append("M.slots = {")
    for i, (ch, code, f) in enumerate(picked):
        key = KEYS[i] if i < len(KEYS) else str(i + 1)
        L.append(f'  {{ key = {lua_str(key)}, char = {lua_str(ch)}, '
                 f'code = {lua_str(code)}, freq = {f} }},')
    L.append("}")
    L.append("")
    L.append("return M")
    L.append("")
    OUT_LUA.parent.mkdir(parents=True, exist_ok=True)
    OUT_LUA.write_text("\n".join(L), encoding="utf-8")


def emit_md(picked):
    total = sum(f for _, _, f in picked)
    rows = "\n".join(
        f"| {i + 1} | `{KEYS[i] if i < len(KEYS) else i + 1}` | {ch} | `{code}` | {f:,} |"
        for i, (ch, code, f) in enumerate(picked))
    out = f"""# yoyo-pure-cj 快捷字条（issue #56）

> 由 `rime/scripts/gen_cj_quickbar.py` 生成。数据源 `rime/yoyo-pure.dict.yaml`。
> 数据文件 `rime/lua/yoyo/data/cj_quickbar.lua`，消费方是 LyraIME 键盘布局（issue #57）。

## 为什么需要它

串击版**取消了编码层的一简**（一击出高频字）。这是硬约束而非取舍：

- 60 个码元已占满单键（26 字母 + 18 独立键 + 16 上滑）；
- 2 码组合被 2 码字占用 97.2%，双击 `XX` 也 100% 冲突。

所以最高频字改由键盘上方的可点字条补偿：点一下直出，不占编码空间，零冲突。

## 12 个字

| # | 键值 | 字 | 最短码 | 字频 |
|---|---|---|---|---|
{rows}

合计字频 {total:,}（占全表单字用量的绝大部分）。

键值 `1`–`9` `0` `-` `=` 只是键盘层的格位标识，不是 Rime 按键；
点击时键盘层用「文本」动作直接送字，不经过串击状态机——因此不需要码。

## 口径

- **字频** = 该字全部条目（含一简）权重的最大值，与 `cj_decision.lua` 完全同法。
  之所以取最大值：字典里 2,472 个字同时有 2 码简码与 3 码全码，字频挂在简码上、
  全码权重为 0，只读全码会把常用字算成冷僻字。
- **码** = 该字最短的可打码（2 码优先）。此码必须存在于判定数据，否则字条点了也打不出来
  ——`test_cj_quickbar.py` 逐条校验这一点。

## 复跑

```
/usr/bin/python3 rime/scripts/gen_cj_quickbar.py
/usr/bin/python3 rime/scripts/test_cj_quickbar.py
```
"""
    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text(out, encoding="utf-8")


def main():
    rows = read_dict()
    picked = build(rows)
    if len(picked) < SLOTS:
        print(f"可用字不足 {SLOTS}（实得 {len(picked)}）", file=sys.stderr)
        return 1
    emit_lua(picked)
    emit_md(picked)
    print("  ".join(f"{ch}({code},{f})" for ch, code, f in picked))
    print(f"→ {OUT_LUA.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
